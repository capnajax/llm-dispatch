function isChatCompletionAllowedTools(o: any): o is ChatCompletionAllowedTools {
  return (
    typeof o === 'object' &&
    o !== null &&
    ['auto', 'required'].includes(o.mode) &&
    Array.isArray(o.tools) &&
    o.tools.every((toolsItem: any) => {
      return typeof toolsItem === 'object' && toolsItem !== null;
    })
  );
}

function isChatCompletionAllowedToolsChoice(
  o: any,
): o is ChatCompletionAllowedToolsChoice {
  return (
    typeof o === 'object' &&
    o !== null &&
    ['allowed_tools'].includes(o.type) &&
    isChatCompletionAllowedTools(o.allowed_tools)
  );
}

function isChatCompletionFunctionCallOption(
  o: any,
): o is ChatCompletionFunctionCallOption {
  return typeof o === 'object' && o !== null && typeof o.name === 'string';
}

function isChatCompletionFunctions(o: any): o is ChatCompletionFunctions {
  return (
    typeof o === 'object' &&
    o !== null &&
    typeof o.description === 'string' &&
    typeof o.name === 'string' &&
    isFunctionParameters(o.parameters)
  );
}

